const wrap = (body: string, size: number): string =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;

export const PG_ICONS = {
  has: (name: string): boolean => name in ICONS,
  svgString: (name: string, size = 16): string => {
    const body = ICONS[name];
    if (!body) {
      console.warn('[lucide] missing icon', name);
      return '';
    }
    return wrap(body, size);
  },
  mount: (el: Element | null, name: string, size?: number): void => {
    if (el) el.innerHTML = PG_ICONS.svgString(name, size);
  },
};

